"""Security overlays. The core is open and agnostic; these are opt-in, except
where an LLM or a stored credential makes them mandatory.

Input overlay (allow-list)
    Off by default: any device may send audio. When on, only identities in
    security.input.allowed get through. Identities must be cryptographic:
      "cert:<common name>"   a Zenoh client certificate (mutual TLS)
      "local:<adapter>"      a device attached to this machine (if local_trusted)
    Names, MAC addresses or IDs inside a payload are NOT accepted: they're easy to fake.

Enforcement rule
    If an LLM is connected or any output uses a stored credential, the input overlay must be on, and
    every network input must be able to prove identity (Zenoh needs mutual TLS).
    Otherwise anyone who can reach the module could spend that credential.
    The module refuses to start and the installer refuses to save in that state.

Output overlay (sign and encrypt)
    For outputs whose path or storage you don't trust (Zenoh routers, files):
    the module signs each message with its own private key, then encrypts it to
    each recipient's public key. Recipients decrypt with their private key and
    verify the signature with the module's public key.
"""

from __future__ import annotations

from dataclasses import dataclass

# Adapters whose source is the machine itself
LOCAL_ADAPTERS = {"stub_mic", "file", "stub_button", "keyboard"}
# Adapters that reach across the network and need cryptographic identity
NETWORK_ADAPTERS = {"zenoh"}


class SecurityError(ValueError):
    pass


@dataclass(frozen=True)
class Identity:
    kind: str  # "cert" | "local"
    name: str

    def __str__(self) -> str:
        return f"{self.kind}:{self.name}"

    @classmethod
    def parse(cls, text: str) -> "Identity":
        kind, _, name = text.partition(":")
        if kind not in ("cert", "local") or not name:
            raise SecurityError(f"Bad identity '{text}'. Use cert:<common name> or local:<adapter>.")
        return cls(kind, name)


def credentialed_outputs(cfg: dict) -> list[str]:
    """Protected outputs: any LLM (even keyless, it's still compute and context worth
    protecting) and any output that carries a stored secret."""
    found = []
    if cfg["llm"]["enabled"]:
        found.append("llm")
    return found


def enforce(cfg: dict) -> None:
    """Raise SecurityError if a credential could be reached by unauthenticated input."""
    creds = credentialed_outputs(cfg)
    if not creds:
        return
    sec = cfg["security"]["input"]
    fix = "Run: stt-tts security allow <identity>  (and stt-tts config set security.input.enabled true)"
    if not sec["enabled"]:
        raise SecurityError(f"Output '{creds[0]}' is protected (an LLM or a stored credential), so input security is "
                            f"required. {fix}")
    if not sec["allowed"] and not sec["local_trusted"]:
        raise SecurityError("Input security is on but nothing is allowed in. " + fix)
    for ident in sec["allowed"]:
        Identity.parse(ident)
    inputs = set(cfg["input"]["adapters"]) | {cfg["control"]["adapter"]}
    if inputs & NETWORK_ADAPTERS and not cfg["zenoh"]["tls"]["enabled"]:
        raise SecurityError("Zenoh input with a credentialed output needs mutual TLS so devices "
                            "can be identified by certificate. Set zenoh.tls.* (see README: Security).")
    if not sec["local_trusted"] and inputs & LOCAL_ADAPTERS:
        local = sorted(inputs & LOCAL_ADAPTERS)
        allowed_local = {Identity.parse(i).name for i in sec["allowed"] if i.startswith("local:")}
        missing = [a for a in local if a not in allowed_local]
        if missing:
            raise SecurityError(f"Local inputs {missing} are not trusted. Allow them with "
                                f"stt-tts security allow local:<adapter>.")


class InputGate:
    """Admits or refuses an input by identity. Open when the overlay is off."""

    def __init__(self, cfg: dict) -> None:
        sec = cfg["security"]["input"]
        self.enabled = sec["enabled"]
        self.local_trusted = sec["local_trusted"]
        self.allowed = {Identity.parse(i) for i in sec["allowed"]}

    def admit(self, identity: Identity | None) -> bool:
        if not self.enabled:
            return True
        if identity is None:
            return False  # unidentified input is refused when the overlay is on
        if identity.kind == "local" and self.local_trusted:
            return True
        return identity in self.allowed

    def admit_adapter(self, adapter_name: str, zenoh_tls: bool) -> bool:
        """Adapter-level check used by the pipeline.

        Zenoh devices are identified per certificate by the router itself: the
        router's access control (generated by `stt-tts security acl`) only lets
        allow-listed certificates publish to the input keys. So a Zenoh input is
        admitted only when mutual TLS is on, i.e. when that check can happen.
        """
        if not self.enabled:
            return True
        if adapter_name in NETWORK_ADAPTERS:
            return zenoh_tls
        return self.admit(Identity("local", adapter_name))


def zenoh_acl(cfg: dict, module_cert: str = "stt-tts") -> dict:
    """Template for zenohd's access_control block, built from the allow-list.

    Default deny. Allow-listed device certificates may publish audio and button
    presses; the module's own certificate may subscribe to them and publish
    its outputs. Check field names against your Zenoh version's documentation.
    """
    keys = cfg["zenoh"]["keys"]
    devices = sorted(Identity.parse(i).name for i in cfg["security"]["input"]["allowed"]
                     if i.startswith("cert:"))
    return {
        "enabled": True,
        "default_permission": "deny",
        "rules": [
            {"id": "devices-publish-input", "messages": ["put"], "flows": ["ingress", "egress"],
             "permission": "allow", "key_exprs": [keys["in_audio"], keys["in_control"]]},
            {"id": "module-reads-input", "messages": ["declare_subscriber", "put"],
             "flows": ["ingress", "egress"], "permission": "allow",
             "key_exprs": [keys["in_audio"], keys["in_control"], keys["tts_text"]]},
            {"id": "module-publishes-output", "messages": ["put"], "flows": ["ingress", "egress"],
             "permission": "allow",
             "key_exprs": [keys["out_text"], keys["tts_audio"], keys["events"]]},
        ],
        "subjects": [
            {"id": "allowed-devices", "cert_common_names": devices},
            {"id": "module", "cert_common_names": [module_cert]},
        ],
        "policies": [
            {"rules": ["devices-publish-input"], "subjects": ["allowed-devices"]},
            {"rules": ["module-reads-input", "module-publishes-output"], "subjects": ["module"]},
        ],
    }


class Sealer:
    """STUB: sign-then-encrypt for outputs listed in security.output.apply_to.

    Planned implementation: PyNaCl (libsodium). Sign with the module's Ed25519
    key, then encrypt to each recipient's X25519 public key (sealed box), so
    only recipients can read it and they can verify it came from this module.
    """

    def __init__(self, cfg: dict) -> None:
        out = cfg["security"]["output"]
        self.enabled = out["seal"]
        self.apply_to = set(out["apply_to"])
        self.recipients = out["recipients"]

    def applies(self, adapter_name: str) -> bool:
        return self.enabled and adapter_name in self.apply_to

    def seal(self, payload: bytes) -> bytes:
        raise NotImplementedError("Output sealing is a stub; see stt_tts/security.py (Sealer).")
